import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {test,before,after} from 'node:test';
import {NestFactory} from '@nestjs/core';
import type {INestApplication} from '@nestjs/common';
import {AppModule} from '../src/app.module.js';
import {AllExceptionsFilter} from '../src/http.js';
import {createPool,adminUrl} from '../src/db.js';
import {assertVolumeReviewDatabase} from './volume-review-fixture.js';
import {internalInspectionFixture} from './internal-inspection-fixture.js';
const admin=createPool(adminUrl);let app:INestApplication,f:Awaited<ReturnType<typeof internalInspectionFixture>>;
const expect=async(p:Promise<any>,status=200)=>{const r=await p;assert.equal(r.status,status,JSON.stringify(r.body));return r.body;};
before(async()=>{await assertVolumeReviewDatabase(admin,true);app=await NestFactory.create(AppModule,{logger:false});app.useGlobalFilters(new AllExceptionsFilter());const server=await app.listen(0,'127.0.0.1');f=await internalInspectionFixture(admin,`http://127.0.0.1:${server.address().port}`);});
after(async()=>{await app?.close();await admin.end();});
test('скрытые работы и субподряд требуют ПТО, даже когда для остальных он выключен',async()=>{
 const policy=`/projects/${f.project}/internal-inspection-policy`;
 const plain=await expect(f.call(policy),200);assert.deepEqual(plain,{required:true,version:0});
 await f.configure();
 const started=await expect(f.action(4,'submit',0),201);assert.equal(started.requirement.reason,'project');assert.equal(started.state,'awaiting_responsibility');
 const off=f.command({expectedVersion:0,required:false}),on=f.command({expectedVersion:0,required:true});
 const raced=await Promise.all([f.call(policy,off,'director'),f.call(policy,on,'director')]);
 assert.deepEqual(raced.map(r=>r.status).sort(),[200,409]);
 const winnerCommand=raced[0].status===200?off:on;
 const replay=await expect(f.call(policy,winnerCommand,'director'));
 assert.deepEqual(replay,raced.find(r=>r.status===200)!.body);
 await expect(f.call(policy,{...winnerCommand,required:raced[0].status===200},'director'),409);
 const disabled=replay.required?await expect(f.call(policy,f.command({expectedVersion:replay.version,required:false}),'director')):replay;
 assert.equal(disabled.required,false);
 const continued=await expect(f.action(4,'responsible',1),201);assert.equal(continued.state,'awaiting_pto');
 const ordinary=await expect(f.call(f.path(0)),200);
 assert.equal(ordinary.requirement.reason,'none');assert.deepEqual(ordinary.allowedActions,[]);
 await expect(f.action(0,'submit',0),422);
 await expect(f.call(f.path(0),f.command({action:'submit',expectedVersion:0,expectedRouteVersion:1,required:false}),'master'),400);
 const created=await f.ok(`/projects/${f.project}/work-types`,f.command({name:'Скрытые QA',unit:'м',requiresRd:false,requiresMaterialControl:false,requiresPredecessorAcceptance:false,requiresId:false,hiddenWork:true}));
 assert.equal(created.hiddenWork,true);
 const kept=await f.ok(`/projects/${f.project}/work-types/${created.id}`,f.command({name:'Скрытые QA',unit:'м',requiresRd:false,requiresMaterialControl:false,requiresPredecessorAcceptance:false,requiresId:false,expectedVersion:created.version,status:'active'}),'director','PUT');
 assert.equal(kept.hiddenWork,true);
 const workType=(await admin.query(`SELECT t.work_type_id FROM daily_tasks t JOIN managed_execution_reports s ON s.tenant_id=t.tenant_id AND s.task_id=t.id WHERE s.report_id=$1`,[f.parts[1].reportId])).rows[0].work_type_id;
 await admin.query(`UPDATE project_work_types SET hidden_work=true WHERE tenant_id=$1 AND id=$2`,[f.tenant,workType]);
 const hidden=await expect(f.call(f.path(1)),200);assert.equal(hidden.requirement.reason,'hidden');assert.equal(hidden.requirement.projectRequired,false);assert.ok(hidden.allowedActions.includes('submit'));
 await expect(f.action(1,'submit',0),201);
 await admin.query(`UPDATE project_work_types SET hidden_work=false WHERE tenant_id=$1 AND id=$2`,[f.tenant,workType]);
 await admin.query(`UPDATE organizations SET kind='subcontractor' WHERE tenant_id=$1 AND id=$2`,[f.tenant,f.org]);
 const subcontract=await expect(f.call(f.path(2)),200);assert.equal(subcontract.requirement.reason,'subcontract');assert.ok(subcontract.allowedActions.includes('submit'));
 await expect(f.action(2,'submit',0),201);
 await admin.query(`UPDATE organizations SET kind='own' WHERE tenant_id=$1 AND id=$2`,[f.tenant,f.org]);
 const restored=await expect(f.call(f.path(3)),200);assert.equal(restored.requirement.reason,'none');
 const foreignTenant=randomUUID(),foreignProject=randomUUID();
 await admin.query(`INSERT INTO tenants(id,name) VALUES($1,'Чужой объект')`,[foreignTenant]);
 await admin.query(`INSERT INTO projects(tenant_id,id,name) VALUES($1,$2,'Чужой')`,[foreignTenant,foreignProject]);
 await expect(f.call(`/projects/${foreignProject}/internal-inspection-policy`,undefined,'director'),404);
 await expect(f.call(policy,undefined,'worker'),403);
 await expect(f.call(policy,f.command({expectedVersion:disabled.version,required:true}),'master'),403);
 await expect(f.call(policy,f.command({expectedVersion:disabled.version,required:'false'}),'director'),400);
});
