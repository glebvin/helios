import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test, before, after } from 'node:test';
import { NestFactory } from '@nestjs/core';
import type { INestApplication } from '@nestjs/common';
import { AppModule } from '../src/app.module.js';
import { AllExceptionsFilter } from '../src/http.js';
import { createPool, adminUrl } from '../src/db.js';
import { assertVolumeReviewDatabase } from './volume-review-fixture.js';
import { internalInspectionFixture } from './internal-inspection-fixture.js';

const pdf = Buffer.from('%PDF-1.1\n1 0 obj<</Type/Catalog>>endobj\ntrailer<</Root 1 0 R>>\n%%EOF\n');
const admin = createPool(adminUrl);
let app: INestApplication, f: Awaited<ReturnType<typeof internalInspectionFixture>>, signer = '';
const expect = async (p: Promise<{ status: number; body: any }>, status = 200) => { const r = await p; assert.equal(r.status, status, JSON.stringify(r.body)); return r.body; };
const root = () => `/projects/${f.project}/accepted-parts/${f.parts[1].partId}/customer-submission`;

before(async () => {
  await assertVolumeReviewDatabase(admin, true);
  app = await NestFactory.create(AppModule, { logger: false });
  app.useGlobalFilters(new AllExceptionsFilter());
  const server = await app.listen(0, '127.0.0.1');
  f = await internalInspectionFixture(admin, `http://127.0.0.1:${(server.address() as { port: number }).port}`);
  signer = randomUUID();
  await admin.query(`INSERT INTO employees(tenant_id,id,organization_id,full_name) VALUES($1,$2,$3,'Подписант компании')`, [f.tenant, signer, f.org]);
  await admin.query(`INSERT INTO employee_project_assignments(tenant_id,project_id,employee_id,status) VALUES($1,$2,$3,'active')`, [f.tenant, f.project, signer]);
  await admin.query(`INSERT INTO responsibility_orders(tenant_id,id,organization_id,project_id,employee_id,order_number,order_date,valid_from,valid_until,document_types,status,version) VALUES($1,$2,$3,$4,$5,'ПР-СК','2026-01-01','2026-01-01','2099-12-31',ARRAY['external-inspection'],'active',1)`, [f.tenant, randomUUID(), f.org, f.project, signer]);
});
after(async () => { await app?.close(); await admin.end(); });

test('мастер записывает полное принятие текущей попытки один раз', async () => {
  await expect(f.call(`/projects/${f.project}/internal-inspection-policy`, f.command({ expectedVersion: 0, required: false }), 'director'), 200);
  await expect(f.call(root(), f.command({ expectedVersion: 0 }), 'master'), 201);
  const missing = await expect(f.call(`${root()}/decision`, f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer }), 'master'), 422);
  assert.equal(missing.error, 'scan_required');
  const scan = await expect(f.call(`${root()}/scans`, f.command({ filename: 'акт.pdf', contentType: 'application/pdf', contentBase64: pdf.toString('base64') }), 'master'), 201);
  const uploaded = await expect(f.call(root(), undefined, 'master'));
  assert.equal(uploaded.decision, null);
  assert.equal(uploaded.scans[0].attemptNumber, 1);
  const remark = await expect(f.call(`${root()}/remarks`, f.command({ body: 'Открытое замечание', responsibleEmployeeId: f.employee, dueOn: '2027-04-01' }), 'master'), 201);
  assert.equal((await expect(f.call(`${root()}/decision`, f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer }), 'master'), 422)).error, 'remarks_open');
  await expect(f.call(`${root()}/remarks/${remark.id}/close`, f.command({}), 'master'), 200);
  assert.equal((await expect(f.call(`${root()}/decision`, f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: f.employee }), 'master'), 422)).error, 'signer_not_authorized');
  assert.equal((await expect(f.call(`${root()}/decision`, f.command({ expectedAttempt: 2, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer }), 'master'), 409)).error, 'stale_version');
  assert.equal((await expect(f.call(`${root()}/decision`, f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer }), 'worker'), 403)).error, 'role_denied');
  assert.equal((await expect(f.call(`${root()}/decision`, f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer }), 'pto'), 403)).error, 'role_denied');
  assert.equal((await expect(f.call(`/projects/${f.otherProject}/accepted-parts/${f.parts[1].partId}/customer-submission/decision`, f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer }), 'master'), 404)).error, 'not_found');
  const body = f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer });
  const saved = await expect(f.call(`${root()}/decision`, body, 'master'), 201);
  assert.equal(saved.decision.attemptNumber, 1);
  assert.equal(saved.decision.quantity, '17.000');
  assert.equal(saved.decision.scanId, scan.fileId);
  assert.equal(saved.decision.customerSignerName, 'Иванов И.И.');
  assert.equal(saved.decision.companySignerName, 'Подписант компании');
  assert.deepEqual(await expect(f.call(`${root()}/decision`, body, 'master'), 201), saved);
  assert.equal((await expect(f.call(`${root()}/decision`, f.command({ expectedAttempt: 1, customerSignerName: 'Иванов И.И.', companySignerEmployeeId: signer }), 'master'), 409)).error, 'already_decided');
  assert.equal((await admin.query(`SELECT count(*)::int n FROM customer_external_decisions WHERE accepted_part_id=$1`, [f.parts[1].partId])).rows[0].n, 1);
  const seen = await expect(f.call(root(), undefined, 'pto'));
  assert.equal(seen.decision.attemptNumber, 1);
  assert.equal(seen.decision.quantity, '17.000');
  assert.equal(seen.decision.scanId, scan.fileId);
  assert.equal((await expect(f.call(`${root()}/remarks`, f.command({ body: 'Новое замечание', responsibleEmployeeId: f.employee, dueOn: f.day }), 'master'), 409)).error, 'already_decided');
  assert.equal((await expect(f.call(root(), f.command({ expectedVersion: 1 }), 'master'), 409)).error, 'already_decided');
  assert.equal((await expect(f.call(`/projects/${f.project}/volume-reviews/${f.parts[1].reportId}/corrections`, f.command({ expectedVersion: 1, previousPartId: f.parts[1].partId, quantity: '16', checklistRunId: f.parts[1].checklistRunId, reason: 'Проверка закрытой части' }), 'master'), 409)).error, 'external_decision_recorded');
  assert.deepEqual((await expect(f.call(root(), undefined, 'pto'))).decision, saved.decision);
});
